--changeset course_project:001-create-items
CREATE TABLE items (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(255) NOT NULL,
                       price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),

                       created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--changeset course_project:002-create-orders
CREATE TABLE orders (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        user_email VARCHAR(255) NOT NULL,
                        status VARCHAR(30) NOT NULL,
                        total_price NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (total_price >= 0),
                        deleted BOOLEAN NOT NULL DEFAULT FALSE,

                        created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

--changeset course_project:003-create-order-items
CREATE TABLE order_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             order_id BIGINT NOT NULL,
                             item_id BIGINT NOT NULL,
                             quantity INTEGER NOT NULL CHECK (quantity > 0),

                             created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT fk_order_items_order
                                 FOREIGN KEY (order_id)
                                     REFERENCES orders(id)
                                     ON DELETE CASCADE,

                             CONSTRAINT fk_order_items_item
                                 FOREIGN KEY (item_id)
                                     REFERENCES items(id)
);

--changeset course_project:004-create-indexes
CREATE INDEX idx_orders_user_id
    ON orders(user_id);

CREATE INDEX idx_orders_status
    ON orders(status);

CREATE INDEX idx_orders_created_at
    ON orders(created_at);

CREATE INDEX idx_orders_deleted
    ON orders(deleted);

CREATE INDEX idx_orders_user_deleted
    ON orders(user_id, deleted);

CREATE INDEX idx_order_items_order_id
    ON order_items(order_id);

CREATE INDEX idx_order_items_item_id
    ON order_items(item_id);

CREATE INDEX idx_items_name
    ON items(name);
